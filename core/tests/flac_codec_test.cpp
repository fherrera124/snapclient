void testFlacDecode() {
  bell::audio::FlacCodec codec;
  bell::audio::FlacConfig config;
  bell::audio::CodecConfig codecConfig = config;

  auto setupRes = codec.setupDecode(bell::audio::Format{}, codecConfig);
  CHECK(setupRes.has_value());

  tcb::span<const std::byte> headerSpan(
      reinterpret_cast<const std::byte*>(kTestFlacData), kMetadataEnd);
  auto headerRes = codec.setupDecodeFromHeaders(headerSpan);
  CHECK(headerRes.has_value());
  if (headerRes) {
    CHECK(*headerRes == bell::audio::Codec::SetupStatus::Ready);
  }

  auto fmt = codec.getAudioFormat();
  CHECK(fmt.getNumChannels() == kExpectedChannels);
  CHECK(fmt.getSampleRateValue() == kExpectedSampleRate);

  tcb::span<const std::byte> framesSpan(
      reinterpret_cast<const std::byte*>(kTestFlacData) + kMetadataEnd,
      sizeof(kTestFlacData) - kMetadataEnd);
  auto decodeRes = codec.decode(framesSpan);
  CHECK(decodeRes.has_value());
  if (decodeRes) {
    CHECK(decodeRes->pcm.size() == kExpectedSamples * sizeof(int16_t));
    CHECK(decodeRes->consumedInputBytes == framesSpan.size());
  }
}

